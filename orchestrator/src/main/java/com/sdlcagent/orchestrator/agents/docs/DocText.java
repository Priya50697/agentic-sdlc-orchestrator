package com.sdlcagent.orchestrator.agents.docs;

import com.sdlcagent.orchestrator.context.CodeIndex;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Parsing and template helpers shared by the DocWriter and the DocsGate. */
final class DocText {
    static final List<String> REQUIRED_SECTIONS = List.of("overview", "api", "running", "testing");
    private static final Pattern ENDPOINT = Pattern.compile("\\b(GET|POST|PUT|PATCH|DELETE)\\s+`?(/[^\\s`|)]*)");
    private static final Pattern HEADING = Pattern.compile("(?m)^#{1,6}\\s+(.+?)\\s*$");

    private DocText() {}

    /** "VERB /path" with path variables normalized to {}; trailing punctuation removed. */
    static String norm(String verb, String path) {
        String p = path.replaceAll("[.,;:]+$", "").replaceAll("\\{[^}]*}", "{}");
        if (p.length() > 1 && p.endsWith("/")) p = p.substring(0, p.length() - 1);
        return verb.toUpperCase() + " " + p;
    }

    static Set<String> documentedEndpoints(String markdown) {
        Set<String> out = new LinkedHashSet<>();
        Matcher m = ENDPOINT.matcher(markdown == null ? "" : markdown);
        while (m.find()) out.add(norm(m.group(1), m.group(2)));
        return out;
    }

    static Set<String> actualEndpoints(CodeIndex index) {
        Set<String> out = new LinkedHashSet<>();
        for (CodeIndex.Endpoint e : index.endpoints()) out.add(norm(e.verb(), e.path().isEmpty() ? "/" : e.path()));
        return out;
    }

    static List<String> headings(String markdown) {
        Matcher m = HEADING.matcher(markdown == null ? "" : markdown);
        List<String> out = new java.util.ArrayList<>();
        while (m.find()) out.add(m.group(1));
        return out;
    }

    static List<String> missingSections(String markdown) {
        List<String> heads = headings(markdown).stream().map(String::toLowerCase).toList();
        return REQUIRED_SECTIONS.stream().filter(req -> heads.stream().noneMatch(h -> h.contains(req))).toList();
    }

    /** Deterministic README used when the LLM path fails: always passes the gate for the code that exists. */
    static String template(String title, CodeIndex index) {
        StringBuilder sb = new StringBuilder("# ").append(title).append("\n\n## Overview\n\n")
                .append("A Spring Boot service generated by the agentic SDLC orchestrator.\n\n## API\n\n");
        for (String e : actualEndpoints(index)) sb.append("- `").append(e).append("`\n");
        sb.append("\n## Running\n\n```\nmvnw spring-boot:run\n```\n\n## Testing\n\n```\nmvnw test\n```\n");
        return sb.toString();
    }
}
